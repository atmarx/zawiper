// bayrules turns the bay configs into the udev rules and unit drop-ins that
// make the kernel enforce each bay's scope (spec §4.1, §8).  It reads them
// with the same parser bayd uses, so the rules and the daemon can't disagree
// about which device a bay is.  deploy/install-bay.sh runs it; nothing else
// should.
//
//	bayrules [-bays /etc/zawiper/bays] -out DIR    write the files to DIR
//	bayrules [-bays /etc/zawiper/bays] -check      just check the configs
//
// DIR gets:
//
//	61-zawiper.rules                                   for /etc/udev/rules.d
//	units/bayd@<bay>.service.d/10-zawiper-device.conf  for /etc/systemd/system
//	bays                                               the bay names, one a line
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"

	"zawiper/internal/config"
)

const systemctl = "/usr/bin/systemctl"

func main() {
	log.SetFlags(0)
	log.SetPrefix("bayrules: ")
	dir := flag.String("bays", config.BaysDir, "where the bay configs are")
	out := flag.String("out", "", "directory to write the rules and drop-ins to")
	check := flag.Bool("check", false, "check the configs and write nothing")
	flag.Parse()

	bays, err := config.LoadBays(*dir)
	if err != nil {
		log.Fatal(err)
	}
	if len(bays) == 0 {
		log.Fatalf("no bays in %s.  Provision one first: see zawiper/README.md", *dir)
	}
	if *check {
		for _, b := range bays {
			fmt.Printf("%-16s %-45s smart %-4s caps %s\n", b.Name, b.Selector(), b.SmartType, strings.Join(b.Caps, ","))
		}
		return
	}
	if *out == "" {
		log.Fatal("-out or -check")
	}
	if err := write(*out, bays); err != nil {
		log.Fatal(err)
	}
}

func write(out string, bays []*config.Bay) error {
	if err := os.MkdirAll(filepath.Join(out, "units"), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(out, "61-zawiper.rules"), []byte(rules(bays)), 0o644); err != nil {
		return err
	}
	var names []string
	for _, b := range bays {
		d := filepath.Join(out, "units", "bayd@"+b.Name+".service.d")
		if err := os.MkdirAll(d, 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(d, "10-zawiper-device.conf"), []byte(dropIn(b)), 0o644); err != nil {
			return err
		}
		names = append(names, b.Name)
	}
	return os.WriteFile(filepath.Join(out, "bays"), []byte(strings.Join(names, "\n")+"\n"), 0o644)
}

const header = `# Za Wiper bays.  Generated by bayrules from %s/*.toml.
# Don't edit: change the bay configs and re-run deploy/install-bay.sh.
#
# For each bay, the device its selector matches gets:
#   /dev/zawiper/<bay>          the disk.  Tagged for systemd, which starts
#                               bayd@<bay> and binds it to this node.
#   /dev/zawiper/<bay>-part%%n   each partition, and
#   /dev/zawiper/<bay>-sg       the SCSI generic node, for SAS tools.
#                               Each is added to bayd@<bay>'s DeviceAllow= as
#                               it comes and goes.
# bayd@<bay> runs with DevicePolicy=closed, so these nodes are the only
# disks it can open, even as root.
#
# The partition and sg rules run on every action.  set-property makes
# systemd rebuild the unit's device filter, and it resolves every
# /dev/zawiper path afresh as it does: a node that has gone drops out, and
# a re-inserted drive's new numbers come in.

# sg nodes don't get ID_PATH from the stock rules; the SAS selectors need it.
SUBSYSTEM=="scsi_generic", ENV{ID_PATH}!="?*", IMPORT{builtin}="path_id"
`

// rules is the udev rules file for every bay.
func rules(bays []*config.Bay) string {
	var sb strings.Builder
	fmt.Fprintf(&sb, header, config.BaysDir)
	for _, b := range bays {
		var match string
		if b.USBPort != "" {
			// Any device whose sysfs path runs through the port, as bay.Sys
			// matches it.  "/10-1/" doesn't match ports 110-1 or 10-12.
			match = fmt.Sprintf(`DEVPATH=="*/usb*/%s/*"`, b.USBPort)
		} else {
			match = fmt.Sprintf(`ENV{ID_PATH}=="%s"`, b.SASPath)
		}
		allow := func(node string) string {
			return fmt.Sprintf(`RUN+="%s --no-ask-password set-property --runtime bayd@%s.service 'DeviceAllow=/dev/zawiper/%s rw'"`,
				systemctl, b.Name, node)
		}
		fmt.Fprintf(&sb, "\n# bay %s: %s\n", b.Name, b.Selector())
		fmt.Fprintf(&sb, `SUBSYSTEM=="block", ENV{DEVTYPE}=="disk", %s, SYMLINK+="zawiper/%s", TAG+="systemd", ENV{SYSTEMD_WANTS}+="bayd@%s.service", ENV{UDISKS_IGNORE}="1"`+"\n",
			match, b.Name, b.Name)
		fmt.Fprintf(&sb, `SUBSYSTEM=="block", ENV{DEVTYPE}=="partition", %s, SYMLINK+="zawiper/%s-part%%n", ENV{UDISKS_IGNORE}="1", %s`+"\n",
			match, b.Name, allow(b.Name+"-part%n"))
		fmt.Fprintf(&sb, `SUBSYSTEM=="scsi_generic", %s, SYMLINK+="zawiper/%s-sg", %s`+"\n",
			match, b.Name, allow(b.Name+"-sg"))
	}
	return sb.String()
}

// dropIn binds bayd@<bay> to its disk.  It's generated rather than written
// into bayd@.service as dev-zawiper-%i.device because a unit name has to
// escape the dash in a bay called "dock-a", and %i doesn't.
func dropIn(b *config.Bay) string {
	dev := escapePath("/dev/zawiper/"+b.Name) + ".device"
	return fmt.Sprintf(`# Generated by bayrules for bay %s (%s).
# Don't edit: re-run deploy/install-bay.sh.
[Unit]
BindsTo=%s
After=%s
`, b.Name, b.Selector(), dev, dev)
}

// escapePath is `systemd-escape --path`: drop the leading slash, turn the
// other slashes into dashes, and \xNN anything else that isn't plain.
func escapePath(p string) string {
	p = strings.Trim(p, "/")
	var sb strings.Builder
	for i := 0; i < len(p); i++ {
		c := p[i]
		switch {
		case c == '/':
			sb.WriteByte('-')
		case c == '.' && i == 0,
			!(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == ':' || c == '_' || c == '.'):
			fmt.Fprintf(&sb, `\x%02x`, c)
		default:
			sb.WriteByte(c)
		}
	}
	return sb.String()
}
